package scope

import (
	"os"
	"path/filepath"
	"testing"

	"ItsBagelBot/pkg/codec"
)

// This fixture is the handshake between the Go resolver inventory
// (CommandTokenFamilies, token_catalog.go) and the kit variables manifest
// (web/kit/lib/variables/): it is read by a bun test there, parity.test.ts,
// so the two inventories cannot drift from each other in either direction.
// Web CI has no Go toolchain and Go CI has no bun, so neither side can assert
// against the other's live code, and a committed fixture is the only surface
// they can both read.
//
// writeGolden (declared in pure_golden_test.go) is reused rather than
// redeclared: it already gates regeneration behind an explicit flag instead
// of a side effect of running the suite, and a second flag with the same
// meaning would just be a second way to get that wrong.

var tokenCatalogGoldenPath = filepath.Join("testdata", "token_catalog.golden.json")

// tokenCatalogGoldenFamily mirrors TokenFamily for JSON purposes: the golden
// file is a stable, versioned artifact, not a serialization of whatever
// fields TokenFamily happens to carry, so it gets its own shape.
type tokenCatalogGoldenFamily struct {
	ID       string   `json:"id"`
	Examples []string `json:"examples"`
	// Aliases is omitted (not emitted as []) for a family with none, so most
	// families' golden entries stay exactly as they were before this field
	// existed.
	Aliases []string `json:"aliases,omitempty"`
}

type tokenCatalogGoldenFile struct {
	Note     string                     `json:"note"`
	Families []tokenCatalogGoldenFamily `json:"families"`
}

const tokenCatalogGoldenNote = "Generated by app/twitch/sesame/engine/scope: go test ./app/twitch/sesame/engine/scope/... " +
	"-run TestTokenCatalogGolden -scope.write-golden. Shared with web/kit/lib/variables/parity.test.ts, so the Go " +
	"resolver inventory and the kit variables manifest cannot drift from each other in either direction."

// TestTokenCatalogGolden asserts CommandTokenFamilies() against the
// committed fixture and, with -scope.write-golden, rewrites it instead.
func TestTokenCatalogGolden(t *testing.T) {
	families := tokenCatalogGoldenFamilies()
	if *writeGolden {
		writeTokenCatalogGolden(t, families)
		return
	}
	assertTokenCatalogGolden(t, families)
}

// tokenCatalogGoldenFamilies converts CommandTokenFamilies() into the
// golden file's shape, preserving family order and each family's example
// order exactly as returned.
func tokenCatalogGoldenFamilies() []tokenCatalogGoldenFamily {
	families := CommandTokenFamilies()
	out := make([]tokenCatalogGoldenFamily, 0, len(families))
	for _, family := range families {
		out = append(out, tokenCatalogGoldenFamily{ID: family.ID, Examples: family.Examples, Aliases: family.Aliases})
	}
	return out
}

func writeTokenCatalogGolden(t *testing.T, families []tokenCatalogGoldenFamily) {
	t.Helper()
	if err := os.MkdirAll(filepath.Dir(tokenCatalogGoldenPath), 0o755); err != nil {
		t.Fatalf("mkdir testdata: %v", err)
	}
	if err := os.WriteFile(tokenCatalogGoldenPath, marshalTokenCatalogGolden(t, families), 0o644); err != nil {
		t.Fatalf("write %s: %v", tokenCatalogGoldenPath, err)
	}
	t.Logf("rewrote %s with %d families", tokenCatalogGoldenPath, len(families))
}

func assertTokenCatalogGolden(t *testing.T, families []tokenCatalogGoldenFamily) {
	t.Helper()
	have, err := os.ReadFile(tokenCatalogGoldenPath)
	if err != nil {
		t.Fatalf("read %s (regenerate with -scope.write-golden): %v", tokenCatalogGoldenPath, err)
	}
	if want := marshalTokenCatalogGolden(t, families); string(have) != string(want) {
		t.Errorf("%s is stale. CommandTokenFamilies() just changed; if that was intended, rerun with "+
			"-scope.write-golden and update web/kit/lib/variables/ to match.", tokenCatalogGoldenPath)
	}
}

func marshalTokenCatalogGolden(t *testing.T, families []tokenCatalogGoldenFamily) []byte {
	t.Helper()
	// codec, not encoding/json: pkg/codec is the fleet's one JSON
	// implementation (a guard test enforces it).
	out, err := codec.MarshalIndent(tokenCatalogGoldenFile{Note: tokenCatalogGoldenNote, Families: families}, "", "  ")
	if err != nil {
		t.Fatalf("marshal golden: %v", err)
	}
	return append(out, '\n')
}
