package modules

import (
	"flag"
	"os"
	"path/filepath"
	"sort"
	"testing"

	"ItsBagelBot/pkg/codec"
)

// writeReplyTokensGolden regenerates testdata/reply_tokens.golden.json
// instead of asserting against it:
//
//	go test ./app/twitch/sesame/modules/... -run TestReplyTokensGolden -modules.write-golden
//
// This fixture is the other half of the cross-language handshake
// engine/scope/token_catalog_golden_test.go documents: it is read by
// web/kit/lib/variables/parity.test.ts's test H, so the Go reply-token
// inventory (ReplyTokenInventory, reply_tokens.go) and the kit catalog's
// replyTokens() namespaces cannot drift from each other in either direction.
// Web CI has no Go toolchain and Go CI has no bun, so a committed fixture is
// the only surface both sides can read.
var writeGolden = flag.Bool("modules.write-golden", false, "rewrite testdata/reply_tokens.golden.json from ReplyTokenInventory()")

var replyTokensGoldenPath = filepath.Join("testdata", "reply_tokens.golden.json")

// replyTokensGoldenFile is the fixture's shape: a human-readable note plus
// the namespace -> sorted token names map. Keys sort themselves on marshal
// (Go's map encoding is always key-sorted), so the inventory's own map order
// never matters here.
type replyTokensGoldenFile struct {
	Note    string              `json:"note"`
	Replies map[string][]string `json:"replies"`
}

const replyTokensGoldenNote = "Generated by app/twitch/sesame/modules: go test ./app/twitch/sesame/modules/... " +
	"-run TestReplyTokensGolden -modules.write-golden. Shared with web/kit/lib/variables/parity.test.ts, so the Go " +
	"reply-token inventory and the kit catalog's replyTokens() namespaces cannot drift from each other in either " +
	"direction."

// TestReplyTokensGolden asserts ReplyTokenInventory() against the committed
// fixture and, with -modules.write-golden, rewrites it instead.
func TestReplyTokensGolden(t *testing.T) {
	inventory := ReplyTokenInventory()
	for ns, names := range inventory {
		sort.Strings(names)
		inventory[ns] = names
	}
	if *writeGolden {
		writeReplyTokensGolden(t, inventory)
		return
	}
	assertReplyTokensGolden(t, inventory)
}

func writeReplyTokensGolden(t *testing.T, inventory map[string][]string) {
	t.Helper()
	if err := os.MkdirAll(filepath.Dir(replyTokensGoldenPath), 0o755); err != nil {
		t.Fatalf("mkdir testdata: %v", err)
	}
	if err := os.WriteFile(replyTokensGoldenPath, marshalReplyTokensGolden(t, inventory), 0o644); err != nil {
		t.Fatalf("write %s: %v", replyTokensGoldenPath, err)
	}
	t.Logf("rewrote %s with %d namespaces", replyTokensGoldenPath, len(inventory))
}

func assertReplyTokensGolden(t *testing.T, inventory map[string][]string) {
	t.Helper()
	have, err := os.ReadFile(replyTokensGoldenPath)
	if err != nil {
		t.Fatalf("read %s (regenerate with -modules.write-golden): %v", replyTokensGoldenPath, err)
	}
	if want := marshalReplyTokensGolden(t, inventory); string(have) != string(want) {
		t.Errorf("%s is stale. ReplyTokenInventory() just changed; if that was intended, rerun with "+
			"-modules.write-golden and update web/kit/lib/variables/parity.test.ts's expectations to match.",
			replyTokensGoldenPath)
	}
}

func marshalReplyTokensGolden(t *testing.T, inventory map[string][]string) []byte {
	t.Helper()
	// codec, not encoding/json: pkg/codec is the fleet's one JSON
	// implementation (a guard test enforces it).
	out, err := codec.MarshalIndent(replyTokensGoldenFile{Note: replyTokensGoldenNote, Replies: inventory}, "", "  ")
	if err != nil {
		t.Fatalf("marshal golden: %v", err)
	}
	return append(out, '\n')
}
