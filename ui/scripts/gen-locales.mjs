import { readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';

const root = resolve(import.meta.dir, '../locales');
const target = join(root, 'index.ts');
const LOCALE = /^[a-z]{2,3}(?:-[a-z0-9]{2,4})?$/;
const FILE = /^[a-z][a-zA-Z0-9_]*\.json$/;

const identifier = (code, name) => `${code.replace('-', '_')}_${name}`;

function locales() {
  return readdirSync(root)
    .filter((name) => LOCALE.test(name) && statSync(join(root, name)).isDirectory())
    .sort();
}

function files(code) {
  return readdirSync(join(root, code))
    .filter((name) => FILE.test(name))
    .map((name) => name.slice(0, -'.json'.length))
    .sort();
}

function render() {
  const codes = locales();
  const imports = codes.flatMap((code) =>
    files(code).map((name) => `import ${identifier(code, name)} from './${code}/${name}.json';`),
  );
  const entries = codes.map((code) => {
    const members = files(code).map((name) => `    ${name}: ${identifier(code, name)},`);
    return `  '${code}': {\n${members.join('\n')}\n  },`;
  });
  return [
    '// Copyright (c) 2026 Adam Ousmer. All rights reserved.',
    '// Proprietary. No license granted. See LICENSE.md.',
    '',
    '// GENERATED by ui/scripts/gen-locales.mjs from ui/locales/<code>/<namespace>.json, do not edit.',
    '',
    ...imports,
    '',
    'export const CATALOG_FILES = {',
    ...entries,
    '} as const;',
    '',
  ].join('\n');
}

const next = render();
if (process.argv.includes('--check')) {
  let current = '';
  try {
    current = readFileSync(target, 'utf8');
  } catch {}
  if (current !== next) {
    console.error('gen-locales: ui/locales/index.ts is stale. Run `bun ui/scripts/gen-locales.mjs` and commit the result.');
    process.exit(1);
  }
  console.log(`locale index is current (${locales().join(', ')})`);
} else {
  writeFileSync(target, next);
  console.log(`gen-locales: wrote ${target}`);
}
