// Writes ui/lib/flags.ts from @iconify-json/circle-flags. Run after editing
// FLAGS or bumping the package, then commit the output:
//
//   bun ui/scripts/gen-flags.mjs
import { writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';

const require = createRequire(import.meta.url);
const set = require('@iconify-json/circle-flags/icons.json');
const { version } = require('@iconify-json/circle-flags/package.json');

// Lowercase ISO 3166-1 region codes.
const FLAGS = ['br', 'de', 'es', 'fr', 'gb', 'ru'];

// Every flag in the set clips itself with the same mask id, so two flags on one
// page would resolve each other's mask. The mask is dropped; CSS clips the disc.
function body(code) {
  const icon = set.icons[code];
  if (!icon) throw new Error(`circle-flags:${code} is not in the set`);
  const out = icon.body
    .replace(/<mask id="[^"]+">.*?<\/mask>/, '')
    .replace(/^<g mask="url\(#[^)]+\)">(.*)<\/g>$/, '$1');
  if (/\bid=|url\(#/.test(out)) throw new Error(`circle-flags:${code} still references an id`);
  return out;
}

const lines = [
  '// Copyright (c) 2026 Adam Ousmer. All rights reserved.',
  '// Proprietary. No license granted. See LICENSE.md.',
  '',
  '// GENERATED by ui/scripts/gen-flags.mjs, do not edit. Values are the inner',
  '// markup of a viewBox="0 0 512 512" SVG, unclipped.',
  `// Source: @iconify-json/circle-flags ${version}.`,
  'export const flags = {',
  ...FLAGS.map((code) => `  ${code}: '${body(code).replace(/'/g, "\\'")}',`),
  '} as const;',
  '',
  'export type FlagCode = keyof typeof flags;',
  '',
  'export function flagBody(code: string | undefined): string | undefined {',
  '  return code && Object.hasOwn(flags, code) ? flags[code as FlagCode] : undefined;',
  '}',
  ''
];

writeFileSync(new URL('../lib/flags.ts', import.meta.url), lines.join('\n'));
