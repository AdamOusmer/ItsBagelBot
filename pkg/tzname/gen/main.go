package main

import (
	"bytes"
	"fmt"
	"go/format"
	"os"
	"runtime"

	"ItsBagelBot/pkg/tzname/internal/zonelist"
)

const outPath = "zones_gen.go"

func main() {
	if err := run(); err != nil {
		fmt.Fprintln(os.Stderr, "gen:", err)
		os.Exit(1)
	}
}

func run() error {
	zones, err := zonelist.Load()
	if err != nil {
		return err
	}
	src, err := render(zones)
	if err != nil {
		return err
	}
	return os.WriteFile(outPath, src, 0o644)
}

func render(zones zonelist.Zones) ([]byte, error) {
	var buf bytes.Buffer
	buf.WriteString("// Copyright (c) 2026 Adam Ousmer. All rights reserved.\n")
	buf.WriteString("// Proprietary. No license granted. See LICENSE.md.\n\n")
	fmt.Fprintf(&buf, "// Code generated by gen/main.go from %s/lib/time/zoneinfo.zip (%s); DO NOT EDIT.\n\n",
		runtime.GOROOT(), runtime.Version())
	buf.WriteString("package tzname\n\n")

	writeSlice(&buf, "canonicalZones", zones.Canonical)
	writeSlice(&buf, "linkZones", zones.Links)

	return format.Source(buf.Bytes())
}

func writeSlice(buf *bytes.Buffer, name string, values []string) {
	fmt.Fprintf(buf, "var %s = []string{\n", name)
	for _, v := range values {
		fmt.Fprintf(buf, "\t%q,\n", v)
	}
	buf.WriteString("}\n\n")
}
