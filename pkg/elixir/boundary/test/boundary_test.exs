defmodule Platform.BoundaryTest do
  use ExUnit.Case, async: true

  test "detects aliases, Erlang calls, captures, behaviours and literal apply" do
    for source <- [
          "Gnat.pub(:name, subject, body)",
          "alias Mint.WebSocket",
          "Redix.command(:name, [])",
          "NewRelic.enabled?()",
          "Protox.encode(message)",
          "Plug.Cowboy.child_spec([])",
          "alias WebSockAdapter",
          ":cow_http.headers([])",
          ":ranch.get_port(:listener)",
          ":cowboy_req.reply(200, %{}, \"\", req)",
          "&:cowboy_req.reply/4",
          "@behaviour :cowboy_websocket",
          ":\"Elixir.Gnat\".pub(:name, subject, body)",
          "apply(:redix, :command, [:name, []])",
          "Jason.encode!(term)",
          ":json.encode(term)",
          "Poison.encode!(term)",
          "Jiffy.decode(json)",
          "Torque.decode(json)",
          ":torque.decode(json)",
          "Thoas.encode(term)",
          "JSON.encode!(term)",
          ":jiffy.decode(json)",
          ":thoas.encode(term)"
        ] do
      assert Platform.Boundary.references(source) != [], source
    end
  end

  test "allows shared packages and connection names that match vendor apps" do
    for source <- [
          "Platform.Nats.publish(:gnat, subject, body)",
          "Platform.WebSocket.Client.connect(url)",
          "Platform.Valkey.ready?(:redix)",
          "Platform.NewRelic.enabled?()",
          "Platform.Cowboy.Server.port(:listener)",
          "Platform.Protobuf.encode(message)",
          "Platform.Sift.encode!(x)",
          "Plug.Conn.send_resp(conn, 200, \"\")"
        ] do
      assert Platform.Boundary.references(source) == [], source
    end
  end

  test "reports each offending file and skips generated sources" do
    dir = Path.join(System.tmp_dir!(), "boundary_#{System.unique_integer([:positive])}")
    File.mkdir_p!(dir)
    on_exit(fn -> File.rm_rf!(dir) end)

    handwritten = Path.join(dir, "handwritten.ex")
    generated = Path.join(dir, "generated.ex")
    File.write!(handwritten, "defmodule A do\n  def f, do: Gnat.pub(:c, \"s\", \"b\")\nend\n")
    File.write!(generated, "# Code generated by protox. DO NOT EDIT.\nProtox.encode(m)\n")

    assert Platform.Boundary.violations([handwritten, generated]) == [{handwritten, Gnat}]
  end
end
