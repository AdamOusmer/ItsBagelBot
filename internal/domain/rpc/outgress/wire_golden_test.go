var writeGolden = flag.Bool("outgress.write-golden", false, "rewrite testdata/wire.json from wireGolden()")

var wireGoldenPath = filepath.Join("testdata", "wire.json")

const wireGoldenNote = "Generated by internal/domain/rpc/outgress: go test ./internal/domain/rpc/outgress/... -run TestWireGolden -outgress.write-golden. " +
	"Read by web/dashboard/src/lib/server/discord-store.test.ts: every *_id key needs a SETUP_FIELDS entry and every non-empty code a DISCORD_CODES entry."

type wireGoldenFile struct {
	Note       string            `json:"note"`
	SetupReply DiscordSetupReply `json:"setup_reply"`
	Codes      []rpc.Code        `json:"codes"`
}

func wireGolden() wireGoldenFile {
	reply := DiscordSetupReply{
		Refused:     "refused",
		DroppedPins: []string{"vip"},
		Fields:      []string{"guild_id"},
		Error:       "error",
		Code:        CodeInvalid,
	}
	ids := reflect.ValueOf(&reply.DiscordSetupIDs).Elem()
	for i := range ids.NumField() {
		ids.Field(i).SetString(ids.Type().Field(i).Name)
	}
	return wireGoldenFile{
		Note:       wireGoldenNote,
		SetupReply: reply,
		Codes: []rpc.Code{
			CodeOK, CodeForbidden, CodeInvalid, CodeNotFound, CodeConflict,
			CodeBoundElsewhere, CodeNotBound, CodeDiscordUnavailable,
			CodeRateLimited, CodeTimeout, CodeUnknown,
		},
	}
}

func TestWireGolden(t *testing.T) {
	out, err := codec.MarshalIndent(wireGolden(), "", "  ")
	if err != nil {
		t.Fatalf("marshal golden: %v", err)
	}
	out = append(out, '\n')
	if *writeGolden {
		if err := os.WriteFile(wireGoldenPath, out, 0o644); err != nil {
			t.Fatalf("write %s: %v", wireGoldenPath, err)
		}
		return
	}
	have, err := os.ReadFile(wireGoldenPath)
	if err != nil {
		t.Fatalf("read %s (regenerate with -outgress.write-golden): %v", wireGoldenPath, err)
	}
	if string(have) != string(out) {
		t.Errorf("%s is stale. The dashboard reads it to check its copy of the setup reply and codes; "+
			"if the wire change was intended, rerun with -outgress.write-golden and update discord-store.ts.", wireGoldenPath)
	}
}

func TestUnbindReplyWireShape(t *testing.T) {
	raw, err := codec.Marshal(DiscordUnbindReply{Code: CodeTimeout})
	if err != nil {
		t.Fatal(err)
	}
	if got := string(raw); got != `{"code":"timeout"}` {
		t.Fatalf("wire = %s", got)
	}
}
