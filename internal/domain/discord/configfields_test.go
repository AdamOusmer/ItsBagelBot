// TestConfigFieldsMatchTheSharedFixture pins Config's JSON tags against
// testdata/config_fields.json, the same file console/shared reads in its own
// test.
//
// The two sides are one JSON object seen from two languages, and nothing in
// either toolchain makes them agree: a field added to Config alone compiles,
// ships, and is dropped on the floor by the dashboard's parser, which is how a
// setting silently stops saving. A field added to the console alone is worse —
// it round-trips through the page and vanishes at the first config.set.
//
// The fixture is not regenerated by this test on purpose (see the
// golden-output rule): a fixture that rewrites itself would go green on
// exactly the change it exists to catch.
func TestConfigFieldsMatchTheSharedFixture(t *testing.T) {
	want := readFieldFixture(t)
	got := configJSONTags(t)
	if !slices.Equal(got, want) {
		t.Fatalf("Config json tags drifted from testdata/config_fields.json\n only in Go:      %v\n only in fixture: %v",
			missing(got, want), missing(want, got))
	}
}

// configJSONTags is the sorted list of Config's JSON field names.
//
// An exported field with no json tag FAILS here rather than being skipped.
// Skipping was the original behaviour and it defeated the point of the
// fixture: Go's encoder falls back to the Go field name, so an untagged
// TicketPanelTitle ships as "TicketPanelTitle", the console writes
// "ticketPanelTitle", and the setting silently stops saving -- with this file
// green, because the field it should have compared was never in the list.
// A deliberate `json:"-"` is still skipped: that is someone saying "not on the
// wire", which is a decision, not an omission.
func configJSONTags(t *testing.T) []string {
	t.Helper()
	rt := reflect.TypeOf(Config{})
	out := make([]string, 0, rt.NumField())
	for i := range rt.NumField() {
		field := rt.Field(i)
		if !field.IsExported() {
			continue
		}
		name, _, _ := cutComma(field.Tag.Get("json"))
		if name == "" {
			t.Fatalf("Config.%s is exported with no json tag; it would ship as %q and the console would never see it",
				field.Name, field.Name)
		}
		if name == "-" {
			continue
		}
		out = append(out, name)
	}
	slices.Sort(out)
	return out
}

func cutComma(tag string) (string, string, bool) {
	for i := range len(tag) {
		if tag[i] == ',' {
			return tag[:i], tag[i+1:], true
		}
	}
	return tag, "", false
}

func readFieldFixture(t *testing.T) []string {
	t.Helper()
	raw, err := os.ReadFile("testdata/config_fields.json")
	if err != nil {
		t.Fatalf("read fixture: %v", err)
	}
	var doc struct {
		Fields []string `json:"fields"`
	}
	if err := codec.Unmarshal(raw, &doc); err != nil {
		t.Fatalf("decode fixture: %v", err)
	}
	return doc.Fields
}

func missing(from, other []string) []string {
	out := []string{}
	for _, v := range from {
		if !slices.Contains(other, v) {
			out = append(out, v)
		}
	}
	return out
}
